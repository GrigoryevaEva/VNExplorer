            // gallery/releases -> Saved/Undo -> browser Back and the original Catalog.
            await page.goto(`${origin}${base}`);
            await page.getByRole('searchbox', { name: 'Search titles' }).fill('story');
            await page.getByRole('searchbox', { name: 'Search titles' }).press('Enter');
            await page.getByRole('radio', { name: 'Russian', exact: true }).check();
            await page.getByRole('button', { name: 'Browse tags' }).click();
            const picker = page.getByRole('dialog', { name: 'Discover tags' });
            await picker.getByRole('button', { name: 'Include Fantasy', exact: true }).click();
            await picker.getByRole('button', { name: 'Done', exact: true }).click();
            await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
            await page.getByRole('button', { name: 'Page 2', exact: true }).click();
            const catalogUrl = page.url();
            assert(
                catalogUrl.includes('q=story') &&
                    catalogUrl.includes('language=ru') &&
                    catalogUrl.includes('tag=g2') &&
                    catalogUrl.includes('page=2')
            );
            await expect(
                page.getByRole('heading', { name: 'Handoff story', exact: true })
            ).toBeVisible();
            await page.screenshot({
                path: join(artifacts, base === '/' ? 'catalog-desktop.png' : 'catalog-subpath.png'),
            });
            await page.getByRole('button', { name: 'Save Handoff story', exact: true }).click();
            await page.getByRole('link', { name: 'Handoff story', exact: true }).click();
            await expect(
                page.getByRole('button', { name: 'Saved Handoff story', exact: true })
            ).toBeVisible();
            await page.getByRole('button', { name: 'Open screenshot 1', exact: true }).click();
            await page.keyboard.press('ArrowRight');
            await expect(page.getByRole('dialog', { name: 'Screenshot viewer' })).toContainText(
                'Screenshot 2 of 2'
            );
            await page.keyboard.press('Escape');
            await expect(
                page.getByRole('button', { name: 'Open screenshot 1', exact: true })
            ).toBeFocused();
            await page.getByRole('button', { name: 'English · 1 release', exact: true }).click();
            const english = page.getByRole('region', { name: 'English releases', exact: true });
            await expect(english.getByText('Partial', { exact: true })).toBeVisible();
            await expect(english.getByText('Machine translation', { exact: true })).toBeVisible();
            await expect(english.getByRole('link', { name: 'First edition' })).toHaveAttribute(
                'href',
                'https://edition.example/'
            );
            await page.screenshot({
                path: join(artifacts, base === '/' ? 'detail-desktop.png' : 'detail-subpath.png'),
                fullPage: true,
            });
            await page.getByRole('link', { name: 'Saved', exact: true }).click();
            await page.getByRole('button', { name: 'Saved Handoff story', exact: true }).click();
            await expect(page.getByText('Your collection starts here.')).toBeVisible();
            await page.getByRole('button', { name: 'Undo', exact: true }).click();
            await expect(
                page.getByRole('heading', { name: 'Handoff story', exact: true })
            ).toBeVisible();
            await page.goBack();
            await expect(
                page.getByRole('heading', { name: 'Handoff story', level: 1 })
            ).toBeVisible();
            await page.getByRole('link', { name: '← Catalog', exact: true }).click();
            await expect(page).toHaveURL(catalogUrl);
            await page.setViewportSize({ width: 390, height: 844 });
            await page.screenshot({
                path: join(
                    artifacts,
                    base === '/' ? 'catalog-mobile.png' : 'catalog-subpath-mobile.png'
                ),
            });
            await page.getByRole('button', { name: 'Filters', exact: true }).click();
            await expect(page.getByRole('button', { name: 'Apply filters' })).toBeVisible();
            await page.keyboard.press('Escape');
            await page.getByRole('link', { name: 'Saved', exact: true }).click();
            await expect
                .poll(() =>
                    page
                        .getByRole('img', { name: 'Handoff story cover', exact: true })
                        .evaluate(
                            (image: HTMLImageElement) => image.complete && image.naturalWidth > 0
                        ))
                .toBe(true);
            await page.screenshot({
                path: join(
                    artifacts,
                    base === '/' ? 'saved-mobile.png' : 'saved-subpath-mobile.png'
                ),
                animations: 'disabled',
            });
            assert(
                assets.some((asset) => asset.url.endsWith('.js')) &&
                    assets.some((asset) => asset.url.endsWith('.css'))
            );
