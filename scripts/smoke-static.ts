import type { Browser, BrowserContext } from '@playwright/test';
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, stat } from 'node:fs/promises';
import { createServer } from 'node:http';
import { extname, isAbsolute, join, relative, resolve, sep } from 'node:path';

import { createTemporaryDirectory } from './lib/temporary-directory.ts';

const ROOT_BASE = '/';
const SUBPATH_BASE = '/novels/';
const MIME_TYPES: Readonly<Record<string, string>> = {
    '.html': 'text/html',
    '.js': 'text/javascript',
    '.css': 'text/css',
    '.svg': 'image/svg+xml',
};

// Test-only static server: only generated bytes and the documented SPA fallback.
// This is never a production application server or an API proxy.
const serve = async (directory: string, base: string) => {
    const server = createServer(async (request, response) => {
        try {
            const path = decodeURIComponent(
                new URL(request.url ?? '/', 'http://localhost').pathname
            );
            if (!path.startsWith(base)) {
                response.writeHead(404).end();
                return;
            }
            const target = resolve(directory, path.slice(base.length) || 'index.html');
            const within = relative(directory, target);
            if (within === '..' || within.startsWith(`..${sep}`) || isAbsolute(within)) {
                response.writeHead(404).end();
                return;
            }
            let file = target;
            try {
                if (!(await stat(file)).isFile()) {
                    throw new Error('Not a file');
                }
            } catch {
                if (extname(path)) {
                    response.writeHead(404).end();
                    return;
                }
                file = join(directory, 'index.html');
            }
            response.writeHead(200, {
                'Content-Type': MIME_TYPES[extname(file)] ?? 'application/octet-stream',
                'Cache-Control': 'no-store',
            });
            response.end(await readFile(file));
        } catch {
            response.writeHead(500).end();
        }
    });
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    const address = server.address();
    assert(address && typeof address !== 'string');
    return { server, origin: `http://127.0.0.1:${address.port}` };
};

